PluginManifest makeUiPluginManifest()
{
	PluginManifest manifest;
	manifest.id = "ui";
	manifest.version = "1.0.0";
	manifest.name = "Built-in GUI";
	manifest.unloadable = false;
	manifest.apply = [](Context& ctx) {
		ctx.effect([]() {
			QtMenuRegistry* menus = &QtMenuRegistry::instance();
			QtPreferencesPageRegistry* preferences = &QtPreferencesPageRegistry::instance();
			SourceGroupUiRegistry* sourceGroups = &SourceGroupUiRegistry::instance();
			QtProjectWizardPageRegistry* wizardPages = &QtProjectWizardPageRegistry::instance();

			const std::vector<std::pair<std::string, QtMenuRegistry::Populator>> menuContributors = {
				{"project",
				 [](QMenu* menu, QtMainWindow* window) { window->populateProjectMenu(menu); }},
				{"edit", [](QMenu* menu, QtMainWindow* window) { window->populateEditMenu(menu); }},
				{"view", [](QMenu* menu, QtMainWindow* window) { window->populateViewMenu(menu); }},
				{"history",
				 [](QMenu* menu, QtMainWindow* window) { window->populateHistoryMenu(menu); }},
				{"bookmarks",
				 [](QMenu* menu, QtMainWindow* window) { window->populateBookmarksMenu(menu); }},
				{"help", [](QMenu* menu, QtMainWindow* window) { window->populateHelpMenu(menu); }},
			};
			for (const auto& [menuId, populator]: menuContributors)
			{
				menus->addContributor(menuId, "core", populator);
			}

			preferences->addPage("core-preferences", [](QtProjectWizardWindow* window) {
				return new QtProjectWizardContentPreferences(window);
			});
#if BUILD_CXX_LANGUAGE_PACKAGE
			preferences->addPage("cxx-header-search", [](QtProjectWizardWindow* window) {
				return new QtProjectWizardContentPathsHeaderSearchGlobal(window);
			});
			if constexpr (utility::Platform::isMac())
			{
				preferences->addPage("cxx-framework-search", [](QtProjectWizardWindow* window) {
					return new QtProjectWizardContentPathsFrameworkSearchGlobal(window);
				});
			}
#endif	  // BUILD_CXX_LANGUAGE_PACKAGE

			addSourceGroupEntries();

			wizardPages->addContributor(
				"core",
				[](QtProjectWizardContentGroup* group,
				   std::shared_ptr<SourceGroupSettings> settings,
				   QtProjectWizard* window) {
					window->populateSourceGroupContents(group, settings);
				});

			const std::vector<std::string> sourceGroupIds = {
				"c-cdb", "c-vs", "c-codeblocks", "c-empty",
				"cxx-cdb", "cxx-vs", "cxx-codeblocks", "cxx-empty",
				"java-maven", "java-gradle", "java-empty",
				"python-empty", "odin-empty", "custom-command"};

			return [menus, preferences, sourceGroups, wizardPages, sourceGroupIds]() {
				for (auto it = sourceGroupIds.rbegin(); it != sourceGroupIds.rend(); ++it)
				{
					sourceGroups->removeEntry(*it);
				}
				wizardPages->removeContributor("core");
				preferences->removePage("cxx-framework-search");
				preferences->removePage("cxx-header-search");
				preferences->removePage("core-preferences");
				for (const std::string& menuId:
					 {"project", "edit", "view", "history", "bookmarks", "help"})
				{
					menus->removeContributor(menuId, "core");
				}
			};
		});
	};
	return manifest;
}

void ensureUiPluginLoaded()
{
	static const bool loaded = globalHost().load(makeUiPluginManifest());
	(void)loaded;
}
